#Operadores matematicos

numero1 = 10
numero2 = 20

#Soma
soma = numero1 + numero2

#subtração
subtracao = numero1 = numero1 - numero2

#Multiplicação
multiplicacao = numero1 = numero1 * numero2

#Divisão
divisao = numero1 = numero1 / numero2
resto = numero1 % numero2

print("Soma dos numeros: ", soma)
print("Subtração dos numeros: ", subtracao)
print("Multiplicação dos numeros: ", multiplicacao)
print("Divisão dos numeros: ", divisao)
print("Resto dos numeros: ", resto)


